import { LocalDate, LocalTime, LocalDateTime, OffsetDateTime } from './date-format';

function integerFromRaw(raw: string, mode: IntegersAsBigInt = 'asNeeded'): number | bigint {
  const compact = raw.replace(/_/g, '');
  let normalized = compact;

  if (/^[+-]?0x/i.test(compact) || /^[+-]?0o/i.test(compact) || /^[+-]?0b/i.test(compact)) {
    const sign = compact[0] === '+' || compact[0] === '-' ? compact[0] : '';
    const body = compact.slice(sign ? 1 : 0);
    normalized = sign + body.toLowerCase();
  }

  let big: bigint | undefined;
  try {
    big = BigInt(normalized);
  } catch {
    // Some integer-valued JS numbers can be stringified in scientific notation
    // (e.g. "5e+22"). BigInt cannot parse that syntax, so preserve behavior
    // by coercing back to Number instead of throwing.
    return Number(compact);
  }

  if (mode === true) {
    return big;
  }
  if (mode === false) {
    return Number(big);
  }
  // 'asNeeded': return number when safe, bigint otherwise
  if (big >= BigInt(Number.MIN_SAFE_INTEGER) && big <= BigInt(Number.MAX_SAFE_INTEGER)) {
    return Number(big);
  }
  return big;
}

/**
 * Recursively tracks nested inline tables as immutable path metadata.
 */
function trackNestedInlineTables(inlineTable: InlineTable, basePath: string[], root: PathState) {
  for (const item of inlineTable.items) {
    const keyValue = item.item;
    if (keyValue.value.type === NodeType.InlineTable) {
      const fullPath = basePath.concat(keyValue.key.value);
      resolvePathState(root, fullPath, true).kind = 'inline';
      trackNestedInlineTables(keyValue.value, fullPath, root);
    }
  }
}

/**
 * Converts a custom Date subclass value to the corresponding Temporal object.
 * Does NOT check for Temporal availability — callers must guard that.
 */
function dateValueToTemporal(value: Date): any {
  // If the value is already a Temporal object (e.g. from a CST generated by
  // parseJS with Temporal input), return it directly — no conversion needed.
  if (value.constructor?.name?.startsWith?.('Temporal.') ||
      value.constructor?.name === 'PlainDate' ||
      value.constructor?.name === 'PlainTime' ||
      value.constructor?.name === 'PlainDateTime' ||
      value.constructor?.name === 'ZonedDateTime') {
    return value;
  }

  const T = (globalThis as any).Temporal;
  // LocalDate → Temporal.PlainDate
  if (value instanceof LocalDate) {
    return T.PlainDate.from(value.toISOString());
  }
  // LocalTime → Temporal.PlainTime
  if (value instanceof LocalTime) {
    return T.PlainTime.from(value.toISOString());
  }
  // LocalDateTime → Temporal.PlainDateTime
  if (value instanceof LocalDateTime) {
    // toISOString() uses a space separator when the original TOML did
    // (useSpaceSeparator flag). Temporal.from() requires T.
    return T.PlainDateTime.from(value.toISOString().replace(' ', 'T'));
  }
  // OffsetDateTime → Temporal.ZonedDateTime
  if (value instanceof OffsetDateTime) {
    // Same: toISOString() uses a space separator when the original TOML did.
    // Normalize to T before extracting the offset and calling .from().
    const iso = value.toISOString().replace(' ', 'T');
    const offsetMatch = iso.match(/([+-]\d{2}:\d{2}|Z)$/);
    const offset = offsetMatch ? offsetMatch[1] : 'Z';
    const plainIso = iso.replace(/([+-]\d{2}:\d{2}|Z)$/, '');
    const tz = offset === 'Z' ? '+00:00' : offset;
    return T.ZonedDateTime.from(`${plainIso}${offset}[${tz}]`);
  }
  // Fallback: native Date or unrecognized Date subclass → Temporal.PlainDateTime
  return T.PlainDateTime.from(value.toISOString().replace('Z', ''));
}

/**
 * Converts the given CST to a JavaScript object.
 * 
 * @param cst The Concrete Syntax Tree to convert.
 * @param input The original input string (used for error reporting).
 * @param opts.integersAsBigInt Controls integer representation.
 * @param opts.temporal When true, date/time values are returned as Temporal objects.
 * @returns The JavaScript object representation of the CST.
 */
export default function toJS(
  cst: CST,
  input: string = '',
  opts: { integersAsBigInt?: IntegersAsBigInt; temporal?: boolean } = {}
): any {
  const { integersAsBigInt = 'asNeeded', temporal = false } = opts;
  const result = blank();
  const pathState = createPathState();
  let active: any = result;
  let active_path: string[] = [];

  for (const block of cst) {
    switch (block.type) {
      case NodeType.Table:
        handleTable(block as Table);
        for (const item of (block as Table).items) {
          if (item.type === NodeType.KeyValue) handleKeyValue(item as KeyValue);
        }
        break;
      case NodeType.TableArray:
        handleTableArray(block as TableArray);
        for (const item of (block as TableArray).items) {
          if (item.type === NodeType.KeyValue) handleKeyValue(item as KeyValue);
        }
        break;
      case NodeType.KeyValue:
        handleKeyValue(block as KeyValue);
        break;
    }
  }

  return result;

  function handleTable(node: Table) {
    const key = node.key.item.value;
    try {
      validateKey(pathState, [], key, node.type);
    } catch (err) {
      throw new ParseError(input, node.key.loc.start, (err as Error).message);
    }
    resolvePathState(pathState, key, true).kind = 'explicit';
    active = ensureTable(result, key);
    active_path = key;
  }

  function handleTableArray(node: TableArray) {
    const key = node.key.item.value;
    try {
      validateKey(pathState, [], key, node.type);
    } catch (err) {
      throw new ParseError(input, node.key.loc.start, (err as Error).message);
    }

    const arrayState = resolvePathState(pathState, key, true);
    arrayState.kind = 'table-array';
    arrayState.entries.push(createPathState());
    active = ensureTableArray(result, key);
    active_path = key;
  }

  function handleKeyValue(node: KeyValue) {
    const key = node.key.value;
    try {
      validateKey(pathState, active_path, key, node.type);
    } catch (err) {
      throw new ParseError(input, node.key.loc.start, (err as Error).message);
    }

    if (key.length > 1) {
      for (let index = 1; index < key.length; index++) {
        const implicit = resolvePathState(pathState, active_path.concat(key.slice(0, index)), true);
        if (implicit.kind === 'undefined') implicit.kind = 'implicit';
      }
    }

    let value;
    try {
      value = toValue(node.value, { integersAsBigInt, temporal });
    } catch (err) {
      throw new ParseError(input, node.value.loc.start, (err as Error).message);
    }

    const fullPath = active_path.concat(key);
    if (node.value.type === NodeType.InlineTable) {
      resolvePathState(pathState, fullPath, true).kind = 'inline';
      trackNestedInlineTables(node.value, fullPath, pathState);
    } else {
      const valueState = resolvePathState(pathState, fullPath, true);
      valueState.kind =
        node.value.type === NodeType.InlineArray
          ? 'array'
          : node.value.type === NodeType.DateTime
            ? 'date'
            : 'value';
      if (node.value.type === NodeType.DateTime) valueState.runtimeValue = value;
    }

    const target = key.length > 1 ? ensureTable(active, key.slice(0, -1)) : active;
    target[last(key)!] = value;
  }
}

/**
 * Converts a TOML CST value node to a JavaScript value.
 * @param node The TOML CST value node.
 * @param opts Options object:
 * @param opts.integersAsBigInt Controls integer representation (`'asNeeded'` | `true` | `false`).
 * @param opts.temporal When `true`, date/time values are returned as Temporal objects
 * @returns The corresponding JavaScript value.
 */
export function toValue(
  node: Value,
  opts: { integersAsBigInt?: IntegersAsBigInt; temporal?: boolean } = {}
): any {
  const { integersAsBigInt = 'asNeeded', temporal = false } = opts;
  switch (node.type) {
    case NodeType.InlineTable:
      const result = blank();
      const defined_keys = new Set<string>();
      const defined_prefixes = new Map<string, string>(); // prefix -> one of the full keys that uses it

      node.items.forEach(({ item }) => {
        const key = item.key.value;
        const value = toValue(item.value, { integersAsBigInt, temporal });

        // Check for duplicate keys and conflicting key paths.  Set lookups use
        // the unambiguous encodeKey form; messages use the `.`-joined display.
        const full_key = joinKey(key);
        const encoded_key = encodeKey(key);

        // Check if this exact key was already defined
        if (defined_keys.has(encoded_key)) {
          throw new Error(`Duplicate key "${full_key}" in inline table`);
        }
        
        // Check if any prefix of this key conflicts with an existing key
        // e.g., if "a.b" is defined, we can't later define "a.b.c" (would overwrite the value)
        for (let i = 1; i < key.length; i++) {
          const prefix = joinKey(key.slice(0, i));
          if (defined_keys.has(encodeKey(key.slice(0, i)))) {
            throw new Error(`Key "${full_key}" conflicts with key: "${prefix}"`);
          }
        }
        
        // Check if this key is a prefix of an already defined key
        // e.g., if "a.b.c" is defined, we can't later define "a.b" (would overwrite the table)
        if (defined_prefixes.has(encoded_key)) {
          const existing = defined_prefixes.get(encoded_key)!;
          throw new Error(`Key "${full_key}" conflicts with key: "${existing}"`);
        }
        
        defined_keys.add(encoded_key);
        
        // Track all prefixes of this key
        for (let i = 1; i < key.length; i++) {
          const encoded_prefix = encodeKey(key.slice(0, i));
          if (!defined_prefixes.has(encoded_prefix)) {
            defined_prefixes.set(encoded_prefix, full_key);
          }
        }

        const target = key.length > 1 ? ensureTable(result, key.slice(0, -1)) : result;
        target[last(key)!] = value;
      });

      return result;

    case NodeType.InlineArray:
      return node.items.map(item => toValue(item.item as Value, { integersAsBigInt, temporal }));

    case NodeType.DateTime:
      if (temporal) {
        if (typeof (globalThis as any).Temporal === 'undefined') {
          throw new Error(
            'Temporal API is not available in this runtime. ' +
            'Set temporal: false or use a runtime with Temporal support.'
          );
        }
        return dateValueToTemporal(node.value);
      }
      // Preserve TOML date/time custom classes so format is retained when
      // round-tripping through stringify() (e.g. date-only, time-only, local vs offset).
      // These classes extend Date, so JS users can still treat them as Dates.
      return node.value;

    case NodeType.String:
      return node.value;

    case NodeType.Integer:
      return integerFromRaw(node.raw, integersAsBigInt);

    case NodeType.Float:
    case NodeType.Boolean:
      return node.value;

    default:
      throw new Error(`Unrecognized value type "${(node as TreeNode).type}"`);
  }
}

function validateKey(
  root: PathState,
  prefix: string[],
  key: string[],
  type: NodeType.Table | NodeType.TableArray | NodeType.KeyValue
) {
  const fullPath = prefix.concat(key);
  const fullName = joinKey(fullPath);
  const target = resolvePathState(root, fullPath);

  for (let index = 0; index < fullPath.length - 1; index++) {
    const path = fullPath.slice(0, index + 1);
    const node = resolvePathState(root, path);
    const nextSegment = fullPath[index + 1];
    const runtimeValue = node.runtimeValue;
    if (
      node.kind === 'date'
      && !node.children.has(nextSegment)
      && runtimeValue !== null
      && typeof runtimeValue === 'object'
      && nextSegment in runtimeValue
    ) {
      throw new Error(`Value already defined for ${joinKey(path.concat(nextSegment))}`);
    }
  }

  if (type === NodeType.KeyValue) {
    if (key.length > 1) {
      for (let index = 1; index < key.length; index++) {
        const path = prefix.concat(key.slice(0, index));
        const node = resolvePathState(root, path);
        const name = joinKey(path);
        if (node.kind === 'inline') throw new Error(`Cannot extend inline table at ${name}`);
        if (node.kind === 'array') throw new Error(`Cannot add to static array at ${name}`);
        if (node.kind === 'table-array') throw new Error(`Cannot traverse Array of Tables at ${name}`);
        if (node.kind === 'value') throw new Error(`Value already defined for ${name}`);
      }
      for (let index = prefix.length + 1; index <= fullPath.length; index++) {
        const path = fullPath.slice(0, index);
        if (resolvePathState(root, path).kind === 'explicit') {
          throw new Error(`Cannot extend explicit table ${joinKey(path)} with dotted keys`);
        }
      }
    }
    if (target.kind === 'implicit' || target.kind === 'explicit') {
      throw new Error(`Table already defined: ${fullName}`);
    }
    if (target.kind === 'table-array') throw new Error(`Table already defined: ${fullName}`);
    if (target.kind === 'value' || target.kind === 'date' || target.kind === 'inline') {
      throw new Error(`Value already defined for ${fullName}`);
    }
    if (target.kind === 'array') throw new Error(`Cannot add to static array at ${fullName}`);
    return;
  }

  for (let index = 1; index < fullPath.length; index++) {
    const path = fullPath.slice(0, index);
    const node = resolvePathState(root, path);
    const name = joinKey(path);
    if (node.kind === 'inline') throw new Error(`Cannot extend inline table at ${name}`);
    if (node.kind === 'array') throw new Error(`Cannot add to static array at ${name}`);
    if (node.kind === 'value') throw new Error(`Value already defined for ${name}`);
  }

  if (target.kind === 'inline') throw new Error(`Cannot extend inline table at ${fullName}`);
  if (target.kind === 'implicit') throw new Error(`Implicit table already defined: ${fullName}`);
  if (target.kind === 'array') throw new Error(`Cannot add to static array at ${fullName}`);
  if (type === NodeType.Table) {
    if (target.kind === 'explicit' || target.kind === 'table-array') {
      throw new Error(`Table already defined: ${fullName}`);
    }
    if (target.kind === 'value' || target.kind === 'date') {
      throw new Error(`Value already defined for ${fullName}`);
    }
  } else if (
    (target.kind !== 'undefined' && target.kind !== 'table-array')
    || (target.kind === 'undefined' && target.children.size > 0)
  ) {
    throw new Error(`Cannot add Array of Tables to table at ${fullName}`);
  }
}

function ensureTable(object: any, key: string[]): any {
  const target = ensure(object, key.slice(0, -1));
  const last_key = last(key)!;
  if (!target[last_key]) {
    target[last_key] = blank();
  }

  return target[last_key];
}

function ensureTableArray(object: any, key: string[]): any {
  const target = ensure(object, key.slice(0, -1));
  const last_key = last(key)!;
  if (!target[last_key]) {
    target[last_key] = [];
  }

  const next = blank();
  target[last(key)!].push(next);

  return next;
}

function ensure(object: any, keys: string[]): any {
  return keys.reduce((active, subkey) => {
    if (!active[subkey]) {
      active[subkey] = blank();
    }
    return Array.isArray(active[subkey]) ? last(active[subkey]) : active[subkey];
  }, object);
}

function joinKey(key: string[]): string {
  return key.join('.');
}

/**
 * Unambiguous encoding of a key path for use as a `Set`/`Map` key.
 *
 * A plain `key.join('.')` collides for distinct key paths: `["", ""]` (an
 * empty-string key nested in an empty-string table) and the single literal
 * segment `["."]` both join to `.`, so a nested empty-key inline table is
 * wrongly rejected when a `["."]` table header follows (fuzz seed 65682).
 */
function encodeKey(key: string[]): string {
  return JSON.stringify(key);
}

type PathStateKind = 'undefined' | 'implicit' | 'explicit' | 'value' | 'date' | 'array' | 'inline' | 'table-array';

type PathState = {
  kind: PathStateKind;
  children: Map<string, PathState>;
  entries: PathState[];
  runtimeValue?: unknown;
};

function createPathState(): PathState {
  return { kind: 'undefined', children: new Map(), entries: [] };
}

function resolvePathState(root: PathState, path: string[], create = false): PathState {
  let node = root;
  for (const segment of path) {
    if (node.kind === 'table-array') node = node.entries[node.entries.length - 1] ?? node;
    let child = node.children.get(segment);
    if (!child && create) {
      child = createPathState();
      node.children.set(segment, child);
    }
    if (!child) return createPathState();
    node = child;
  }
  return node;
}
